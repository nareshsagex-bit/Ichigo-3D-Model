import assert from 'node:assert/strict';
import * as THREE from 'three';
import {attachModelFocus,focusableMesh,focusDistance} from '../src/controls/modelFocus.js';

const root=new THREE.Group();root.position.x=2;
const mesh=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshBasicMaterial());root.add(mesh);
const hidden=new THREE.Group();hidden.visible=false;root.add(hidden);
const hiddenMesh=mesh.clone();hidden.add(hiddenMesh);
assert.equal(focusableMesh(hiddenMesh,root),false);
const aura=new THREE.Group();aura.name='Character reiatsu aura';root.add(aura);
const auraMesh=mesh.clone();aura.add(auraMesh);
assert.equal(focusableMesh(auraMesh,root),false);
const handles=new THREE.Group();handles.name='Hand drag handles';root.add(handles);
const handleMesh=mesh.clone();handles.add(handleMesh);
assert.equal(focusableMesh(handleMesh,root),false);
assert.equal(focusableMesh(mesh,root),true);
assert.ok(focusDistance(new THREE.Vector3(3,-9,0))<focusDistance(new THREE.Vector3(0,-4,0)));

const handlers=new Map();
const canvas={addEventListener(name,callback){handlers.set(name,callback);},getBoundingClientRect(){return {left:10,top:20,width:800,height:600};}};
const camera=new THREE.PerspectiveCamera(38,800/600,0.1,100);
camera.position.set(2,0,10);camera.lookAt(2,0,0);
const orbit={enabled:true,target:new THREE.Vector3(2,0,0)};
let count=0,enabled=true;
const focus=attachModelFocus(root,camera,canvas,orbit,{onFocus:()=>count++,enabled:()=>enabled});
const event={button:0,pointerId:1,clientX:410,clientY:320};
const emit=(name,e=event)=>handlers.get(name)(e);
emit('pointerdown');emit('pointerup');
for(let i=0;i<120;i++)focus.update(1/60);
assert.equal(count,1,'A model click must focus');
assert.ok(orbit.target.distanceTo(new THREE.Vector3(2,0,0.5))<1e-5,'Focus must use the world-space surface hit');
assert.ok(Math.abs(camera.position.distanceTo(orbit.target)-3.6)<1e-5,'Head inspection must frame a useful detail distance');
emit('pointerdown');emit('pointermove',{...event,clientX:430});emit('pointerup');
assert.equal(count,1,'Orbit drags must not trigger focus');
enabled=false;emit('pointerdown');emit('pointerup');assert.equal(count,1);
enabled=true;orbit.enabled=false;emit('pointerdown');emit('pointerup');assert.equal(count,1,'Hand dragging must not trigger focus');
orbit.enabled=true;emit('pointerdown',{...event,clientX:12,clientY:22});emit('pointerup',{...event,clientX:12,clientY:22});
assert.equal(count,1,'Background clicks must not move the camera');
console.log('Model focus: world-space picking, useful framing, hidden/effect exclusions, drag separation, disabled mode and background clicks passed.');
